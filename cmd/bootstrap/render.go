package main

import (
	"fmt"
	"os"
	"strings"
)

const (
	goListPath = "cmd/server/enabled_plugins.go"
	tsListPath = "web/src/plugins/enabled-plugins.ts"
)

// renderGo is cmd/server/enabled_plugins.go for a selection: blank imports, so
// each plugin's init() registers it. Empty selection = the committed core-only file.
func renderGo(sel []manifest) []byte {
	var b strings.Builder
	b.WriteString("package main\n\n// Code generated by cmd/bootstrap. DO NOT EDIT.\n// The plugins compiled into this build. Committed core-only.\n")
	if len(sel) == 0 {
		return []byte(b.String())
	}
	b.WriteString("\nimport (\n")
	for _, m := range sel {
		fmt.Fprintf(&b, "\t_ %q\n", m.Import)
	}
	b.WriteString(")\n")
	return []byte(b.String())
}

// renderTS is web/src/plugins/enabled-plugins.ts for a selection: each plugin's
// React half registers into the slots. Empty selection = the committed file.
func renderTS(sel []manifest) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/bootstrap. DO NOT EDIT.\n// The plugins compiled into this build. Committed core-only.\n")
	if len(sel) == 0 {
		b.WriteString("export {}\n")
		return []byte(b.String())
	}
	b.WriteString("import { slots } from './slots'\n")
	for _, m := range sel {
		fmt.Fprintf(&b, "import %s from './%s'\n", m.Key, m.Key)
	}
	b.WriteString("\n")
	for _, m := range sel {
		fmt.Fprintf(&b, "%s(slots)\n", m.Key)
	}
	return []byte(b.String())
}

// renderDemoTS is the Demo Room build's list: every plugin is compiled in, and
// each registers only when the page's shop has it on (pluginOn reads the list
// the demo injects). Shop builds never use it.
func renderDemoTS(sel []manifest) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/bootstrap. DO NOT EDIT.\n// The Demo Room build: every plugin, on per shop. Committed core-only.\n")
	b.WriteString("import { slots } from './slots'\nimport { pluginOn } from './active'\n")
	for _, m := range sel {
		fmt.Fprintf(&b, "import %s from './%s'\n", m.Key, m.Key)
	}
	b.WriteString("\n")
	for _, m := range sel {
		fmt.Fprintf(&b, "if (pluginOn('%s')) %s(slots)\n", m.Key, m.Key)
	}
	return []byte(b.String())
}

// writeSelection writes both generated lists for sel.
func writeSelection(goPath, tsPath string, sel []manifest) error {
	if err := os.WriteFile(goPath, renderGo(sel), 0o644); err != nil {
		return err
	}
	return os.WriteFile(tsPath, renderTS(sel), 0o644)
}

// withSelection writes both lists for sel, runs build, and always writes them
// back core-only — even when the build fails — so a shop's plugin set never
// lingers in the working tree to be committed by accident.
func withSelection(goPath, tsPath string, sel []manifest, build func() error) (err error) {
	defer func() {
		if rerr := writeSelection(goPath, tsPath, nil); rerr != nil && err == nil {
			err = fmt.Errorf("restore core-only plugin lists: %w", rerr)
		}
	}()
	if err := writeSelection(goPath, tsPath, sel); err != nil {
		return err
	}
	return build()
}
